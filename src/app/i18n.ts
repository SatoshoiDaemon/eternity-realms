export type TranslationKey = keyof typeof translations;

export function t(key: TranslationKey): string {
  return translations[key];
}

export function userFacingError(error: unknown): string {
  if (!(error instanceof Error) || !error.message.trim()) return t('error.generic');

  const message = error.message.trim();
  if (message.startsWith('Unknown session:')) return t('error.session.missing');
  if (message.startsWith('Unknown activity:') || message.startsWith('Unknown reward:')) {
    return t('error.content.missing');
  }
  if (message.startsWith('Session duration must be')) return t('error.session.duration');
  if (message === 'There is no active session to cancel.') return t('error.session.noActive');
  if (message.startsWith('A character is required')) {
    return t('error.session.characterRequired');
  }
  if (message === 'Database unavailable.' || message === 'sqlite transaction failed') {
    return t('error.generic');
  }
  return message;
}
